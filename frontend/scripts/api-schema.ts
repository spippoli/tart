/**
 * Generates the API client types from the committed OpenAPI schema (ADR 0004).
 *
 *     node scripts/api-schema.ts    (pnpm api:generate)
 *
 * The schema itself comes from the backend; a backend test fails when it drifts
 * from the API, and a unit test here fails when these types drift from it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

export const schemaFile = new URL('../src/lib/api/openapi.json', import.meta.url);
export const typesFile = new URL('../src/lib/api/schema.d.ts', import.meta.url);

const header =
	'// Generated by `pnpm api:generate` from openapi.json with openapi-typescript. Do not edit.\n\n';

export async function generateApiTypes(): Promise<string> {
	const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
	return header + astToString(await openapiTS(schema));
}

if (import.meta.main) {
	writeFileSync(typesFile, await generateApiTypes());
}
